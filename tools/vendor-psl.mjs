// Vendors the Public Suffix List (https://publicsuffix.org, MPL-2.0) into
// extension/background/psl.js, which the wipe uses to tell which part of a host
// name is the registrable site (impots.gouv.fr, not gouv.fr).
//
//   node tools/vendor-psl.mjs                 download, check PSL_SHA256, write
//   node tools/vendor-psl.mjs --from <file>   use a local copy instead
//
// To update: download the new list, read its changes, put its SHA-256 into
// PSL_SHA256 below and run this again. A list whose hash does not match is refused.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

export const PSL_URL = 'https://publicsuffix.org/list/public_suffix_list.dat';
export const PSL_SHA256 = '017501d3fa7911c60ac7e0f68df4122b07216c585c15dc30e0f0c74b8d13a2b9';
const OUT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..', 'extension', 'background', 'psl.js');

// Rules as browsers see host names: Unicode labels in punycode, lower case.
export function compactRules(text) {
  const rules = [];
  for (const raw of text.split('\n')) {
    const line = raw.trim().split(/\s/)[0];
    if (!line || line.startsWith('//')) continue;
    const prefix = line.startsWith('!') ? '!' : '';
    const body = prefix ? line.slice(1) : line;
    const wild = body.startsWith('*.') ? '*.' : '';
    const name = wild ? body.slice(2) : body;
    const ascii = url.domainToASCII(name);
    if (!ascii) throw new Error(`cannot convert rule: ${line}`);
    rules.push(prefix + wild + ascii.toLowerCase());
  }
  return [...new Set(rules)].sort();
}

async function main() {
  const i = process.argv.indexOf('--from');
  const buf = i > -1 ? fs.readFileSync(process.argv[i + 1]) : Buffer.from(await (await fetch(PSL_URL)).arrayBuffer());
  const hash = crypto.createHash('sha256').update(buf).digest('hex');
  if (hash !== PSL_SHA256) {
    process.stderr.write(`vendor-psl: SHA-256 ${hash} does not match PSL_SHA256. Review the list, then update PSL_SHA256.\n`);
    process.exit(1);
  }
  const rules = compactRules(buf.toString('utf8'));
  const body =
    '// Generated by tools/vendor-psl.mjs from the Public Suffix List\n' +
    `// (${PSL_URL}, SHA-256 ${PSL_SHA256}).\n` +
    '// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0.\n' +
    '// If a copy of the MPL was not distributed with this file, You can obtain one at\n' +
    '// https://mozilla.org/MPL/2.0/. Do not edit.\n' +
    `export const PSL_RULES = ${JSON.stringify(rules.join('\n'))};\n`;
  fs.writeFileSync(OUT, body);
  process.stdout.write(`${rules.length} rules -> ${path.relative(process.cwd(), OUT)}\n`);
}

if (process.argv[1] === url.fileURLToPath(import.meta.url)) await main();
